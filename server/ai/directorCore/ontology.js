/**
 * 导演核 · 镜头语言本体
 * ============================================================================
 * 这个文件里没有"词典"，只有**设计决策**。
 * 每一条常量都必须能回答同一个问题：它为什么存在？
 *
 * 三条不可让渡的立场（本内核与"把剧本句子切开"式分镜的根本分歧）：
 *
 *   I.   镜头的原子是「观看事件」，不是句子。
 *        一个镜头存在的唯一理由，是它让观众获得了一次别的镜头无法交付的观看。
 *
 *   II.  切镜的本质是「视点位移」。位移发生在五维坐标系里
 *        （距离 / 角度 / 归属 / 关系 / 时间）。五维都不动却切了，就是假切镜。
 *
 *   III. 运镜不是装饰，是「注意力的移动轨迹」。
 *        运镜必须回答：摄影机为什么要动？答不上来，就固定。
 *
 * 一切派生自这三条。凡与之冲突的规则，一律删除，而不是打补丁。
 */

/* ==========================================================================
 * 一、景别阶梯 —— 不是分类，是一条连续的「信息半径」标尺
 * --------------------------------------------------------------------------
 * radius = 该景别在画面里能容纳的「信息半径」，单位是人体宽度。
 * 9 = 山川湖海；1 = 一根手指。景别选择因此变成一个可比较的量：
 * 观众此刻需要看多近的东西？由被看对象的信息尺度决定，不由导演的偏好决定。
 * ========================================================================== */

