export const SIZE_BY_KEY = Object.fromEntries(SHOT_SIZES.map((s) => [s.key, s]))
export const SIZE_ORDER = SHOT_SIZES.map((s) => s.key)

/** 由信息半径反查最贴合的景别（就近取档） */
export function sizeForRadius(radius) {
  let best = SHOT_SIZES[0]
  let bestD = Infinity
  for (const s of SHOT_SIZES) {
    const d = Math.abs(s.radius - radius)
    if (d < bestD) { bestD = d; best = s }
  }
  return best.key
}

/** 景别位移量：0 = 没动，1 = 跨一档，越大越说明"这是一次真位移" */
export function sizeShift(a, b) {
  const ia = SIZE_ORDER.indexOf(a)
  const ib = SIZE_ORDER.indexOf(b)
  if (ia < 0 || ib < 0) return 0
  return Math.abs(ia - ib)
}

