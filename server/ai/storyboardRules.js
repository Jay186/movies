export function styleLockRule(styleLabel = '', styleCategory = '') {
  const label = String(styleLabel || '').trim()
  // 词表与豁免口径的唯一权威源在 storyboardValidator（本文件只引用，不复制正文）
  const exempt = styleExemptWords(label, styleCategory)
  const zhForbidden = STYLE_POISON_ZH.filter((w) => !exempt.zh.has(w))
  const enForbidden = STYLE_POISON_EN.filter((w) => !exempt.en.has(w))
  const ownNote = label
    ? `本项目画风为「${label}」：该画风自身的风格词（用于锁定画风）不在禁止之列，只禁止【切换到别的画风】。`
    : ''
  return '\n\n【画风统一铁律（与台词铁律同级，违反即输出无效）】\n'
    + '1. 全片所有镜头（含武戏/变身/异变/回忆/梦境）必须使用同一画风——即项目指定的画风，禁止任何镜头切换到其他画风。\n'
    + `2. ${ownNote}描述与 integratedMultimodalDescription 中禁止出现下列【风格切换词】：${zhForbidden.join('、')}，以及 ${enForbidden.join(' / ')}。\n`
    + '3. 剧情需要"变强/异变/变身/暴怒"时，只能通过画面内容表达：体型暴涨、毛发炸立、眼睛发红、蒸汽升腾、环境特效（碎屑/光效/烟尘），画风保持不变。\n'
    + '4. "压迫感/重量感"等演出需求写成画面与动作语言（towering scale / real weight and inertia），不得借道画风切换。'
}

