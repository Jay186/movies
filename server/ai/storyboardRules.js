/**
 * 集级镜头语言规格注入
 * @param {string} notes - episodes.director_notes（空串返回 ''，不改变原行为）
 * @param {object} opts
 * @param {'strict'|'gentle'} opts.mode - strict=创作/补全（硬约束，优先级最高）；
 *        gentle=文件规整（上下文校准：只校准措辞，不虚构/不反转用户原意）
 */
export function directorNotesPrompt(notes, { mode = 'strict' } = {}) {
  const spec = String(notes || '').trim()
  if (!spec) return ''
  if (mode === 'gentle') {
    return '\n\n【集级镜头语言规格（上下文参考）】本集导演指定：' + spec
      + '\n规整 cameraMovement 与机位措辞时，若用户原文方向/机位与该规格冲突，按规格校准措辞（例如规格为"持续下坡"，则"跟拍"可规整为"低机位持续下坡跟拍"）；'
      + '但不得虚构用户没有写过的动作，也不得反转用户已明确表达的画面含义。'
  }
  return '\n\n【镜头语言规格（全片硬约束，优先级最高）】\n'
    + '本集导演指定：' + spec + '\n'
    + '必须做到：\n'
    + '1. 每个镜头的 cameraMovement 与 integratedMultimodalDescription 模块1 的机位/运动方向都服从上述规格，禁止与之矛盾；\n'
    + '2. 同一场次内相邻镜头之间，运动方向与机位高度变化必须连续衔接：上一镜在持续下坡，下一镜就不得出现爬升、急拉机位或反向运动；机位大幅变化只能作为显式转场设计出现在镜头边界，并注明"这是转场设计"；\n'
    + '3. 规格中的方向/物理信息要落进动作时间轴（模块4）与最终画面（finalFrame/模块6），例如"路沿坡向下延伸、机位随坡均匀下降"，不能只停留在声明里；\n'
    + '4. 所有景别（含近景/特写）都继承全片方向，不得靠反向移动背景制造虚假的方向感。'
}
