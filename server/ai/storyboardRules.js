// 单镜动作密度硬约束（V3 出片对齐）：时长换不来动作数，动作一多 H3 必糊。
// 背景：实测「雪山大战白熊」1-6 镜 8 秒塞 5 动作 + 3 句台词，出片动作被优化器截短后糊掉。
// 核心结论：H3 单镜能稳定演准的核心动作约 2~3 个，超过即丢动作；多角色同时发力必须拆镜。
// 2026-09-19 第五轮对齐：旧条款只写"核心动作 ≤2~3 个"，与校验侧 ACTION_DENSITY_HIGH
// （肢体动作动词 ÷ 时长 ≤0.6）是两套口径，模型无法自检——第2集重提 35 镜实测 7 条密度告警，
// 模型按"核心动作 4 个"自认合格、按 QC 口径却是 1.1 个/秒。现补第 5/6 条把上限写成同口径可数式。
export function actionDensityRule() {
  return '\n\n【单镜动作密度硬约束（与台词铁律同级，违反即输出无效）】\n'
    + '1. 单镜核心动作数 ≤2~3 个。核心动作 = 一个角色完成一个完整动作单元（「扑抱」「抡拳」「甩头」「竖起围巾」各算一个）。'
    + '（本条是给创作直觉用的近似说法；【机械计数一律以第 5 条为准】，两条口径不一致时按更严的执行——不要用"核心动作只有 3 个"当理由绕过第 5 条的肢体动作动词上限。）\n'
    + '2. 一镜出现 ≥2 个角色各自独立发力的核心动作时（如 A 扑抱、B 抡拳同时发生），必须按角色拆成两镜，每镜只承载一个角色的发力动作，靠 Airlock 衔接。\n'
    + '3. 台词与动作同镜时动作数降到 1~2 个，优先保证台词能念全。\n'
    + '4. 时长不能替代动作数：把 5 个动作塞进 15 秒同样会糊，拆镜才是正解。\n'
    + '5. 【可数上限 · 输出前必须自己数一遍】本镜 description 里的肢体动作动词总数 ÷ 时长（秒）≤0.6。'
    + '换算成各时长的硬上限：5 秒≤3 个、6 秒≤3 个、7 秒≤4 个、8 秒≤4 个、9 秒≤5 个、10 秒≤6 个。'
    + '肢体动作动词 = 扑抓推拉撞甩跳摔跑走坐站转缩抖躲举放抱拍打踢咬爬滚跌滑退拽凑蹭跃冲踩钻攀压低挺起竖起凑近起身迈步挪落下张开攥揪抠抵扳刨砸这类逐帧可见的肢体位移；'
    + '「看/听见/想到/开口说」这类不含肢体位移的动词不计数。'
    + '超过上限时按这个顺序处理：【先判断这些动作是否属于同一任务的连续链】（如听见声音→判断方向→循声走去）——是同一条链，就优先加长时长到「动作数 ÷ 0.6」以上，不要拆（拆了会和【一镜一任务 ≠ 一个动作一镜】打架）；'
    + '只有当这些动作分属多个独立任务时，才按任务边界拆镜。加时长与拆镜都不做 = 违反本条。\n'
    + '6. 【合并 ≠ 搬运】把两镜并成一镜时，必须同步删掉中间态过程描写（重复的"退回岸边""被推得偏了半尺"这类），只留任务链的端点动作；合并后的动作数仍受第 5 条约束。'
    + '合并是为了「一个完整视觉任务一镜到底」，不是把两镜的内容倒进一镜——只并镜号不删动作，等于把两镜的负荷叠到一条时间轴上，出片只会更糊。'
}

// 镜头语言硬约束（电影感规则，2026-09-18 升级为七层美学心法）：
// 管"文戏节拍"与"景别节奏"——actionDensityRule 只管武戏发力动作，
