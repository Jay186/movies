// ===== 为什么单独成文件 =====
//
// 本文件装的是**中文语言知识**，不是项目专属词，也不是算法逻辑。
// 它回答的是"中文里哪些词属于雾/光/位移"这类**语言学问题**，
// 与"这部片子叫雪山还是都市"无关，也与"怎么比较两场戏"无关。
//
// 分离动机：
//   - 换语言（英/日）只需新增 ja-JP.js，算法与项目词典都不动；
//   - 调词表不必碰算法文件，降低改坏风险；
//   - 词表是数据，可以被复用、审查、版本化。
//
// ===== 维护铁律（血泪换来的，改动前必读）=====
//
// 1. **禁止单字词**。单字会命中无关复合词。实测事故：
//    - 词表含「石」→ "河滩碎石/湿石"命中石族 → 木桥被误判为石桥
//    - 词表含「谷」→ "溪谷"被判为垂直地形 → 误报跨层位移
//    - 词表含「下」→ "顺流而下"被判为垂直地形 → 误报
//    - 词表含「留」→ "雾留在半山腰"被当成"过渡已交代" → 该报的不报（静默空转）
//    - 词表含「返」→ "反复"被当成位移动词 → 无位移过程的戏被判合规
//    必须用 2 字以上词组。
//
//    ⚠️ 唯一的例外：**误命中方向是"漏报"的族**可以留单字（当前只有 env.weather 的
//       雪/雨/风/冰/沙）。判据是"错了会往哪边错"——
//       · 会**误报/误豁免**的族（transition / moveVerbs / verticalTerrain / placeNoise）：
//         单字一律删，改词组；
//       · 只会**漏报**的族（weather）：单字比漏检安全，保留。
//       同一份"禁单字"铁律不能一刀切，方向不同处理必须不同。
//
// 2. **区分"地点"与"位移"**。「溪谷」「缓坡」是**地形地名**（进 placeNouns）；
//    「谷底」「陡坡」表示**上下层级**（进 verticalTerrain）。混用必误报。
//
// 3. **改完必须三回归**：
//    node _audit_continuity_real.mjs     # 真实数据零误报
//    node _audit_continuity_generic.mjs  # 跨题材仍有效
//    node _audit_continuity_regress.mjs  # 历史 bug 仍抓得住

