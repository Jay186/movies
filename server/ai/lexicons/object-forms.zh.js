//
// ===== 这是什么 =====
//
// 「同一物体跨场出现时，材质/结构族必须一致」这条检查，需要知道两件事：
//   1. 哪些**物体**值得查（桥、门、船…）
//   2. 每个物体的**形态族**怎么分（木/石/铁…）
//
// 这是**内容判断**，既不是算法（怎么做比较），也不是纯语言知识（中文里雾有哪些词）。
// 故独立成文件，可按项目/题材替换。
//
// ===== 通用性说明 =====
//
// 这里只收"跨题材都可能出现"的物体。项目专属物体（宝鼎/机甲/灵舟）
// 应通过 opts.lexicon.objects 注入，**不要往这里加**——
// 加了就会让模块带上某个题材的偏见。
//
// ===== 维护铁律（血泪换来的）=====
//
// **形态词必须是 2 字以上的词组，禁止单字。**
// 实测事故：形态词含单字「石」→ 场2 的"河滩碎石/湿石"命中石族
// → "木桥 → 断桥"这个本该干净的场景误报 OBJECT_FORM_INCONSISTENT。
